package neoLegacy

import "testing"

func TestAddressFromCompressedPublicKey(t *testing.T) {
	pubKey := []byte{
		0x02, 0x5d, 0x3f, 0x7f, 0x46, 0x98, 0x03, 0xc6, 0x8c, 0x12, 0xb8,
		0xf7, 0x31, 0x57, 0x6c, 0x74, 0xa9, 0xb5, 0x30, 0x84, 0x84, 0xfd,
		0x3b, 0x42, 0x5d, 0x87, 0xc3, 0x5c, 0xae, 0xd0, 0xa2, 0xe3, 0x98,
	}

	script := getVerificationScript(pubKey)
	if len(script) != len(pubKey)+2 || script[0] != 0x21 || script[len(script)-1] != 0xac {
		t.Fatalf("unexpected verification script: %x", script)
	}

	address := Address(pubKey)
	if len(address) == 0 || address[0] != 'A' {
		t.Fatalf("unexpected NEO address: %s", address)
	}
}
